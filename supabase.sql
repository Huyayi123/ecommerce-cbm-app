returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, display_name, role)
  values (new.id, coalesce(new.email, ''), coalesce(new.raw_user_meta_data->>'display_name', new.email, ''), 'viewer')
  on conflict (id) do nothing;
  return new;
end;
$$;

